class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


def heading(text, level=0):
    key = 'h_' + hashlib.md5(text.encode()).hexdigest()[:8]
    style = S['h1'] if level == 0 else S['h2']
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1_block(text, first_body=None):
    """H1 + accent underline + orphan protection."""
    items = [heading(text, 0),
             HRFlowable(width='100%', color=ACCENT, thickness=1.4,
                        spaceBefore=2, spaceAfter=10)]
    if first_body is not None:
        items.append(first_body)
    return [CondPageBreak(H1_ORPHAN), KeepTogether(items)]


def body(text):
    return Paragraph(text, S['body'])


def bullet(text):
    return [Paragraph(f'•  {text}', S['bullet'])]


def make_table(header, rows, ratios, caption=None, align_center_cols=()):
    data = [[Paragraph(f'<b>{h}</b>', S['th']) for h in header]]
    for r in rows:
        row = []
        for ci, cell in enumerate(r):
            st = S['td_c'] if ci in align_center_cols else S['td']
            row.append(Paragraph(cell, st))
        data.append(row)
    widths = [x * AVAIL_W for x in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 12), t]
    if caption:
        out += [Spacer(1, 2), Paragraph(caption, S['caption']), Spacer(1, 10)]
    else:
        out += [Spacer(1, 12)]
    return out


def stat_row(stats):
    """Three-metric callout row."""
    cells = []
    for value, label in stats:
        inner = Table(
            [[Paragraph(f'<b>{value}</b>', S['stat'])],
             [Paragraph(label, S['statlabel'])]],
            colWidths=[(AVAIL_W - 24) / 3],
        )
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, -1), (-1, -1), 9),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        cells.append(inner)
    wrap = Table([cells], colWidths=[AVAIL_W / 3] * 3, hAlign='CENTER')
    wrap.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
    ]))
    return [Spacer(1, 6), wrap, Spacer(1, 12)]


def figure_pair(path_a, path_b, caption):
    """Two portrait screenshots side by side with caption."""
    max_h = 250
    imgs = []
    for p in (path_a, path_b):
        from PIL import Image as PILImage
        w, h = PILImage.open(p).size
        ratio = min((AVAIL_W * 0.42) / w, max_h / h, 1.0)
        imgs.append(Image(p, width=w * ratio, height=h * ratio))
    t = Table([[imgs[0], imgs[1]]], colWidths=[AVAIL_W / 2, AVAIL_W / 2],
              hAlign='CENTER')
    t.setStyle(TableStyle([
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    return [KeepTogether([t, Paragraph(caption, S['caption'])])]


