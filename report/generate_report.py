# ============ 8. Limitations ============
story += h1_block('8. Technical Limitations', body(
    'The evaluation surfaced honest limitations that a decision-maker '
    'should weigh alongside the capabilities. None of them is a blocker '
    'for the complement strategy, but each would need work before the '
    'engine served production jobs.'))
story += bullet('<b>No official headless CLI.</b> Motion Canvas ships no command-line '
                'renderer. The prototype\u2019s harness closes the gap using public APIs, but it '
                'is custom code that must be maintained across Motion Canvas upgrades.')
story += bullet('<b>Version coupling.</b> The harness depends on internal-by-convention '
                'surfaces (the project meta exporter registry, the plugin\u2019s websocket '
                'export endpoint). A Motion Canvas major release could require harness '
                'adjustments; the dependency is pinned at 3.17.2 for stability.')
story += bullet('<b>2D depth is stylised, not true 3D.</b> The 2.5D look comes from '
                'parallax layers, gradients, and drawn side faces. Real perspective or '
                'lighting changes would require a 3D renderer, which is outside this scope.')
story += bullet('<b>Linear render time.</b> Wall time scales with duration at about '
                '18-19 frames per second for a 375-node scene; heavier scenes will be '
                'slower. Long episodes need either scene budgets or sharded rendering.')
story += bullet('<b>Memory per render.</b> About 1.5-1.7 GB of resident Chrome memory '
                'per concurrent render; runner concurrency must be capped at two renders '
                'per standard 16 GB machine.')
story += bullet('<b>Text rendering quirks.</b> Canvas font strings do not quote family '
                'names, so font families with spaces silently fall back to serif. The '
                'prototype works around this by registering a space-free family name '
                '(Baloo2); the rule is documented for future scenes.')
story += bullet('<b>No audio or caption pipeline yet.</b> The prototype is silent by '
                'design. Narration muxing, background music ducking, and word-timed '
                'captions - all mature in the current renderer - are future work with a '
                'documented integration surface.')

